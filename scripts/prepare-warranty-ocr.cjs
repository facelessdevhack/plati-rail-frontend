const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '..')
const target = path.join(root, 'public/warranty-ocr')
fs.mkdirSync(target, { recursive: true })
const packageRoot = name => path.dirname(require.resolve(name + '/package.json'))
const copy = (source, destination) => fs.cpSync(source, path.join(target, destination), { recursive: true })
copy(path.join(packageRoot('tesseract.js'), 'dist/worker.min.js'), 'worker.min.js')
const core = packageRoot('tesseract.js-core')
fs.mkdirSync(path.join(target, 'core'), { recursive: true })
for (const file of fs.readdirSync(core).filter(name => /\.wasm(?:\.js)?$/.test(name))) copy(path.join(core, file), 'core/' + file)
copy(path.join(packageRoot('@tesseract.js-data/eng'), '4.0.0_best_int/eng.traineddata.gz'), 'lang/eng.traineddata.gz')
const pdf = packageRoot('pdfjs-dist')
copy(path.join(pdf, 'legacy/build/pdf.mjs'), 'pdf.mjs')
copy(path.join(pdf, 'legacy/build/pdf.worker.min.mjs'), 'pdf.worker.min.mjs')
for (const directory of ['standard_fonts', 'cmaps', 'wasm']) copy(path.join(pdf, directory), directory)
console.log('Warranty-card OCR assets prepared for local browser processing.')
